CREATE TABLE event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id     BIGINT       NOT NULL REFERENCES venue (id),
    organiser_id BIGINT       NOT NULL REFERENCES users (id),
    title        VARCHAR(200) NOT NULL,
    starts_at    TIMESTAMPTZ  NOT NULL,
    status       VARCHAR(20)  NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ,
    cancelled_at TIMESTAMPTZ,
    version      BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_event_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CANCELLED'))
);

-- Price of every section for one event, fixed when the event is created. Copied into each
-- event_seat on publish, so later edits never change the price of a seat already on sale.
CREATE TABLE event_section_price (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id    BIGINT NOT NULL REFERENCES event (id),
    section_id  BIGINT NOT NULL REFERENCES section (id),
    price_paise BIGINT NOT NULL CHECK (price_paise >= 0),
    CONSTRAINT uq_event_section_price UNIQUE (event_id, section_id)
);

-- One row per venue seat per published event. This is the row M4 locks when holding seats.
-- Ids come from a pooled sequence like seat; the publish INSERT ... SELECT calls nextval per row.
CREATE SEQUENCE event_seat_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE event_seat (
    id          BIGINT      PRIMARY KEY,
    event_id    BIGINT      NOT NULL REFERENCES event (id),
    seat_id     BIGINT      NOT NULL REFERENCES seat (id),
    section_id  BIGINT      NOT NULL REFERENCES section (id),
    price_paise BIGINT      NOT NULL CHECK (price_paise >= 0),
    status      VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE',
    version     BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_event_seat UNIQUE (event_id, seat_id),
    CONSTRAINT ck_event_seat_status CHECK (status IN ('AVAILABLE', 'HELD', 'SOLD'))
);
