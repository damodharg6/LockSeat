CREATE TABLE venue (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(120) NOT NULL,
    city       VARCHAR(80)  NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_venue_name ON venue (name);

CREATE TABLE section (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venue_id BIGINT      NOT NULL REFERENCES venue (id),
    name     VARCHAR(60) NOT NULL,
    CONSTRAINT uq_section_venue_name UNIQUE (venue_id, name)
);

-- Seats are inserted in bulk; ids come from a pooled sequence so Hibernate can batch inserts.
CREATE SEQUENCE seat_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE seat (
    id          BIGINT     PRIMARY KEY,
    section_id  BIGINT     NOT NULL REFERENCES section (id),
    row_label   VARCHAR(3) NOT NULL,
    seat_number INTEGER    NOT NULL CHECK (seat_number > 0),
    CONSTRAINT uq_seat_position UNIQUE (section_id, row_label, seat_number)
);
